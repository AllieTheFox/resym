//! Names of the registers CodeView records refer to by number (`CV_HREG_e`).
//!
//! The values come from `cvconst.h` (DIA SDK). Only registers that can hold a
//! variable are listed: general purpose, segment and flags registers, vector
//! and floating point registers, and the parts of vector registers holding
//! scalars (`xmm0_0`: element 0 of xmm0, `xmm1l`: low 64 bits of xmm1).

/// `CV_ALLREG_VFRAME`: x86 "virtual frame", the frame of functions using
/// frame pointer omission
pub const CV_ALLREG_VFRAME: u16 = 30006;

/// Returns the name of a register of the given machine, if known.
pub fn register_name(machine_type: pdb::MachineType, register: u16) -> Option<&'static str> {
    if register == CV_ALLREG_VFRAME {
        return Some("vframe");
    }
    let registers = match machine_type {
        pdb::MachineType::X86 => X86_REGISTERS,
        pdb::MachineType::Amd64 => AMD64_REGISTERS,
        pdb::MachineType::Arm | pdb::MachineType::ArmNT => ARM_REGISTERS,
        pdb::MachineType::Arm64 => ARM64_REGISTERS,
        _ => return None,
    };
    registers
        .binary_search_by_key(&register, |(value, _)| *value)
        .ok()
        .map(|index| registers[index].1)
}

